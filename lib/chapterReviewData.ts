// Helper to get questions for a specific chapter
export function getQuestionsForChapter(chapterId: string): QuizQuestion[] {
  const chapter = CHAPTER_REVIEW_LIST.find((c) => c.id === chapterId);
  if (!chapter) return [];

  const result: QuizQuestion[] = [];
  const addedQuestions = new Set<string>();

  // 1. Get slide quizzes from the corresponding slide deck
  const deck = NAKDHAMMA_TRI_DECKS.find((d) => d.id === chapter.deckId);
  if (deck) {
    deck.slides.forEach((slide) => {
      if (slide.quiz && !addedQuestions.has(slide.quiz.question.trim())) {
        addedQuestions.add(slide.quiz.question.trim());
        result.push({
          id: `slide-q-${chapter.id}-${slide.id}`,
          grade: 'ตรี',
          subject: chapter.subjectTitle,
          year: 'หลักสูตรแม่กองธรรมสนามหลวง',
          question: slide.quiz.question,
          options: slide.quiz.options,
          correctIndex: slide.quiz.correctIndex,
          explanation: slide.quiz.explanation,
          reference: slide.categoryTag ? `${chapter.subjectTitle} (${slide.categoryTag})` : chapter.title,
          sourceName: 'หลักสูตรธรรมศึกษาและนักธรรมชั้นตรี แม่กองธรรมสนามหลวง',
          sourceUrl: '/curriculum/tri/1-267.pdf'
        });
      }
    });
  }

  // 2. Match past exam questions from QUIZ_QUESTIONS for ชั้นตรี
  const triPool = QUIZ_QUESTIONS.filter((q) => q.grade === 'ตรี');

  // Matcher rules per chapter
  const matchesChapter = (q: QuizQuestion): boolean => {
    const text = `${q.reference} ${q.question} ${q.subject}`;
    switch (chapter.id) {
      case 'chap-dhamma-01':
        return /หมวด ๒|หมวด ๓|โอวาท|รัตนะ|กุศลมูล|บุญกิริยา|ไตรลักษณ์|โลกบาล/i.test(text);
      case 'chap-dhamma-02':
        return /หมวด ๔|อริยสัจ|พรหมวิหาร|อิทธิบาท|สังคหวัตถุ|ฆราวาสธรรม|สติปัฏฐาน|สัมมัปปธาน/i.test(text);
      case 'chap-dhamma-03':
        return /หมวด ๕|หมวด ๖|หมวด ๗|หมวด ๘|ขันธ์ ๕|นิวรณ์ ๕|สัปปุริสธรรม|มรรค ๘|โลกธรรม/i.test(text);
      case 'chap-dhamma-04':
        return /คิหิปฏิบัติ|มิตร|ทิศ ๖|อบายมุข|ทิฏฐธัม/i.test(text);
      case 'chap-dhamma-05':
        return /อุดม|อริยทรัพย์|พละ ๕|อธิษฐานธรรม|อัปปมัญญา|บุญกิริยาวัตถุ ๑๐|ทศพิธราชธรรม/i.test(text);
      case 'chap-buddha-01':
        return (q.subject.includes('พุทธ')) && /ปริเฉท ๑|ปริเฉท ๒|ปริเฉท ๓|ประสูติ|ศากย|ผนวช|ตรัสรู้/i.test(text);
      case 'chap-buddha-02':
        return (q.subject.includes('พุทธ')) && /ปริเฉท ๔|ปริเฉท ๕|ปริเฉท ๖|สัตตมหาสถาน|ปฐมเทศนา|ปัญจวัคคีย์|พระยส/i.test(text);
      case 'chap-buddha-03':
        return (q.subject.includes('พุทธ')) && /ปริเฉท ๗|ปริเฉท ๘|มัชฌิม|ปรินิพพาน|ถวายพระเพลิง/i.test(text);
      case 'chap-buddha-04':
        return (q.subject.includes('พุทธ')) && /สังคายนา/i.test(text);
      case 'chap-ceremony-01':
        return /โต๊ะหมู่|เครื่องสักการะ|จุดธูป|อาราธนา/i.test(text);
      case 'chap-ceremony-02':
        return /ทำบุญ|วันสำคัญ|ถวายทาน|ภัตตาหาร|กฐิน|ผ้าป่า/i.test(text);
      case 'chap-vinai-01':
        return /ศีล ๕|เบญจศีล|ปาณา|อทินนา|กาเม|มุสา|สุรา|อุโบสถศีล/i.test(text);
      case 'chap-vinai-02':
        return /เบญจธรรม|เมตตา|สัมมาอาชีวะ|กามสังวร|สัจจะ|สติสัมปชัญญะ/i.test(text);
      case 'chap-vinai-03':
        return (q.subject.includes('วินัย')) && /ปาราชิก|สังฆาทิเสส|อนิยต|อาบัติ ๗/i.test(text);
      case 'chap-vinai-04':
        return (q.subject.includes('วินัย')) && /นิสสัคคิย|ปาจิตตีย|ปาฏิเทสนีย|เสขิย|อธิกรณ/i.test(text);
      case 'chap-kratu-01':
        return q.subject.includes('กระทู้');
      default:
        return false;
    }
  };

  triPool.forEach((q) => {
    if (matchesChapter(q) && !addedQuestions.has(q.question.trim())) {
      addedQuestions.add(q.question.trim());
      result.push(q);
    }
  });

  return result;
}
