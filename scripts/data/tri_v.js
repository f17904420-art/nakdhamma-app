function generateTriV() {
  const combined = [...rawTriVPart1, ...rawTriVPart2, ...rawTriVPart3, ...rawTriVPart4];
  if (combined.length !== 100) {
    throw new Error(`Expected 100 questions for tri-v, got ${combined.length}`);
  }
  return combined.map((item, idx) => {
    return createQuestion({
      id: `tri-v-${String(idx + 1).padStart(3, '0')}`,
      grade: 'ตรี',
      subject: 'วินัย',
      year: item.year,
      question: item.q,
      correct: item.c,
      distractors: item.d,
      explanation: item.e,
      reference: item.ref,
      targetIndex: idx % 4
    });
  });
}

